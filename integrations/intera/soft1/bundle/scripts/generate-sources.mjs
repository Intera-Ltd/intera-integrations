// Regenerates src/data-sources/soft1-sources.generated.ts from a running Intera.Soft1.Api:
//
//   node scripts/generate-sources.mjs [serviceUrl] [serviceToken]
//   (defaults: http://localhost:8080, local-dev-token)

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const baseUrl = (process.argv[2] ?? 'http://localhost:8080').replace(/\/+$/, '');
const token = process.argv[3] ?? 'local-dev-token';
const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data-sources', 'soft1-sources.generated.ts');

const TYPES = { Text: 'string', Number: 'number', Date: 'date', Flag: 'boolean' };

const response = await fetch(`${baseUrl}/api/Schema/sources`, {
  headers: { Authorization: `Bearer ${token}` },
});
if (!response.ok) {
  throw new Error(`GET /api/Schema/sources answered ${response.status}`);
}

const { data: sources } = await response.json();
const literal = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const lines = [
  '// GENERATED by scripts/generate-sources.mjs from Intera.Soft1.Api (Models/Soft1Sources.cs) - do not edit by hand.',
  '',
  "import type { IDataSourceFieldDescriptor } from '../types';",
  '',
  'export interface ISoft1SourceDefinition {',
  '  /** The source id on the API side: `POST /api/Source/{apiSource}/query`. */',
  '  apiSource: string;',
  '  name: string;',
  '  description: string;',
  '  fields: IDataSourceFieldDescriptor[];',
  '}',
  '',
  'export const SOFT1_SOURCES: ISoft1SourceDefinition[] = [',
];

for (const source of sources) {
  lines.push('  {');
  lines.push(`    apiSource: ${literal(source.id)},`);
  lines.push(`    name: ${literal(source.name)},`);
  lines.push(`    description: ${literal(source.description)},`);
  lines.push('    fields: [');
  for (const field of source.fields) {
    const parts = [`name: ${literal(field.name)}`, `type: '${TYPES[field.type]}'`, `label: ${literal(field.label)}`];
    if (field.lookup) {
      parts.push(
        `lookup: { datasource: ${literal(`soft1_${field.lookup}`)}, valueField: ${literal(field.lookup_value)}, ` +
          `labelField: ${literal(field.lookup_label)} }`,
      );
    }
    lines.push(`      { ${parts.join(', ')} },`);
  }
  lines.push('    ],');
  lines.push('  },');
}

lines.push('];', '');
writeFileSync(target, lines.join('\n'));

const fieldCount = sources.reduce((sum, source) => sum + source.fields.length, 0);
console.log(`${sources.length} sources, ${fieldCount} fields -> ${target}`);
