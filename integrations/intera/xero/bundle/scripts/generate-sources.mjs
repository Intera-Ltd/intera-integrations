// Regenerates src/data-sources/xero-sources.generated.ts from a running Intera.Xero.Api:
//
//   node scripts/generate-sources.mjs [apiBaseUrl] [accessToken]
//   (defaults: http://localhost:8108, local-dev-token - the API's Development settings)
//
// The API's Models/XeroSources.cs is the one list of sources and fields; this file is its copy on the plugin side.
// A field the API does not know is refused there, and a field it serves that is missing here never reaches the
// host's picker - so the copy is generated rather than kept by hand. It reads GET /api/Schema/sources, which needs
// no Xero connection.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const baseUrl = (process.argv[2] ?? 'http://localhost:8108').replace(/\/+$/, '');
const token = process.argv[3] ?? 'local-dev-token';
const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data-sources', 'xero-sources.generated.ts');

const TYPES = { Text: 'string', Number: 'number', Date: 'date', Flag: 'boolean' };

const response = await fetch(`${baseUrl}/api/Schema/sources`, { headers: { 'X-Access-Token': token } });
if (!response.ok) {
  throw new Error(`GET /api/Schema/sources answered ${response.status}: ${await response.text()}`);
}

const { data: sources } = await response.json();
const literal = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const lines = [
  '// GENERATED by scripts/generate-sources.mjs from Intera.Xero.Api (Models/XeroSources.cs) - do not edit by hand.',
  '',
  "import type { IDataSourceFieldDescriptor } from '../types';",
  '',
  'export interface IXeroSourceDefinition {',
  '  /** The source id on the API side: `POST /api/Source/{apiSource}/query`. */',
  '  apiSource: string;',
  '  name: string;',
  '  description: string;',
  '  fields: IDataSourceFieldDescriptor[];',
  '}',
  '',
  'export const XERO_SOURCES: IXeroSourceDefinition[] = [',
];

for (const source of sources) {
  lines.push('  {');
  lines.push(`    apiSource: ${literal(source.id)},`);
  lines.push(`    name: ${literal(source.name)},`);
  lines.push(`    description: ${literal(source.description)},`);
  lines.push('    fields: [');
  for (const field of source.fields) {
    const parts = [`name: ${literal(field.name)}`, `type: '${TYPES[field.type]}'`, `label: ${literal(field.label)}`];
    if (field.lookup) {
      parts.push(
        `lookup: { datasource: ${literal(`xero_${field.lookup}`)}, valueField: ${literal(field.lookup_value)}, ` +
          `labelField: ${literal(field.lookup_label)} }`,
      );
    }
    lines.push(`      { ${parts.join(', ')} },`);
  }
  lines.push('    ],');
  lines.push('  },');
}

lines.push('];', '');
writeFileSync(target, lines.join('\n'));

const fieldCount = sources.reduce((sum, source) => sum + source.fields.length, 0);
console.log(`${sources.length} sources, ${fieldCount} fields -> ${target}`);
